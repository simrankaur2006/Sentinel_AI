"""Deterministic analysis provider. Needs no model and never contacts a network."""
from __future__ import annotations

from collections import Counter
from typing import Any

from app.ai.base import AnalysisResult, injection_warnings
from app.detection.rules import is_internal
from app.mitre.mapping import merge_mappings

HYPOTHESES = {
    "R-AUTH-001": "The source may be guessing credentials (brute force or password spraying). A misconfigured client, stale saved password or shared NAT address could produce the same pattern.",
    "R-AUTH-002": "The account may have been accessed with a guessed or stolen credential. The legitimate user recovering from typing errors would look identical in these logs.",
    "R-AUTH-003": "The account may be used from unexpected places or times. Travel, VPN changes or shift work are common benign explanations.",
    "R-NET-001": "The source may be enumerating open services. An authorized scanner or monitoring system could explain it.",
    "R-NET-002": "The internal host may be communicating with an address on the watchlist, possibly command-and-control. The watchlist entry may be stale or inaccurate.",
    "R-NET-003": "A large amount of data may have left the environment. Backups, updates or legitimate uploads could explain the volume; the logs do not show content.",
    "R-ACC-001": "A user or process may be probing sensitive files. Misconfigured jobs or administrators with insufficient permissions could explain denied accesses.",
    "R-COR-001": "Several detections converge on the same entity, which raises priority and may reflect staged activity. The link is circumstantial and the alerts may have unrelated causes.",
    "ML-IFOREST": "The event is statistically unusual compared to the rest of the data. Rare does not mean malicious.",
}
MISSING = {
    "R-AUTH-001": "Identity-provider or account lockout logs to confirm the credential state of the targeted accounts.",
    "R-AUTH-002": "Post-login activity for the account (commands, file access, new sessions) to show what happened after the login.",
    "R-AUTH-003": "Geolocation/ownership of the source IPs and the user's historical login pattern beyond this dataset.",
    "R-NET-001": "Firewall response data showing which probed ports were open, and whether any probe led to a session.",
    "R-NET-002": "Process-level or DNS/proxy telemetry from the internal host identifying what generated the traffic, plus the origin of the watchlist entry.",
    "R-NET-003": "Payload, proxy or DLP telemetry showing what was transferred and who owns the destination.",
    "R-ACC-001": "File-system audit logs confirming whether any read of the sensitive paths succeeded.",
    "ML-IFOREST": "A longer behavioral baseline for this host/user; the model only compares events within the analysed dataset.",
}


def _refs(alert: dict[str, Any], n: int = 5) -> list[str]:
    return [alert["ref"]] + alert.get("event_refs", [])[:n]


class DeterministicProvider:
    name = "deterministic-fallback"

    def analyze(self, context: dict[str, Any]) -> AnalysisResult:
        inc = context["incident"]
        alerts = context["alerts"]
        res = AnalysisResult(generator=self.name)
        if not alerts:
            res.summary = f"Incident {inc['ref']} ('{inc['title']}') has no linked alerts, so there is nothing to analyse yet."
            res.missing_evidence.append("Link at least one alert to this incident.")
            return res

        sev = Counter(a["severity"] for a in alerts)
        sev_txt = ", ".join(f"{sev[s]} {s}" for s in ("Critical", "High", "Medium", "Low") if sev[s])
        first = min(a["first_seen"] for a in alerts)
        last = max(a["last_seen"] for a in alerts)
        users = sorted({u for a in alerts for u in a.get("usernames", [])})
        ips = sorted({i for a in alerts for i in a.get("ips", [])})
        top = sorted(alerts, key=lambda a: (-{"Critical": 4, "High": 3, "Medium": 2, "Low": 1}.get(a["severity"], 0), a["first_seen"]))[:3]
        res.summary = (
            f"Incident {inc['ref']} ('{inc['title']}') groups {len(alerts)} alert(s) ({sev_txt}) between {first} and {last} (UTC). "
            f"Entities seen in the evidence: users {', '.join(users[:8]) or 'none recorded'}; IPs {', '.join(ips[:8]) or 'none recorded'}. "
            f"Highest-priority alerts: {'; '.join(a['ref'] + ' ' + a['title'] for a in top)}. "
            f"{len(context.get('notes', []))} analyst note(s) are attached. This summary was generated by fixed templates, not a language model."
        )

        for a in alerts:
            res.why_flagged.append({"alert_ref": a["ref"], "text": a["explanation"]})
            res.observed_facts.append({"text": f"{a['ref']} ({a['severity']}, {a['detection_source']}): {a['description']}", "refs": _refs(a)})
            h = HYPOTHESES.get(a["rule_id"])
            if h:
                res.hypotheses.append({"text": h, "refs": [a["ref"]]})
            if a["severity"] in ("Critical", "High"):
                res.containment.extend(self._containment(a))

        seen: set[str] = set()
        for a in alerts:
            for s in a.get("recommended_steps", []):
                if s not in seen:
                    seen.add(s)
                    res.investigation_steps.append(s)
            m = MISSING.get(a["rule_id"])
            if m and m not in res.missing_evidence:
                res.missing_evidence.append(m)
        if ips:
            res.missing_evidence.append("Asset ownership for the internal IPs and independent reputation/ownership data for external IPs.")
        if not users:
            res.missing_evidence.append("No usernames were present in the evidence, so account-level scoping is not possible.")
        res.mitre = merge_mappings([a.get("mitre", []) for a in alerts])
        res.referenced_alerts = [a["ref"] for a in alerts]
        res.referenced_events = sorted({r for a in alerts for r in a.get("event_refs", [])[:50]})
        res.warnings = injection_warnings(context)
        if context.get("truncated"):
            res.warnings.append("The context was truncated; some alerts or events are not reflected here.")
        return res

    @staticmethod
    def _containment(a: dict[str, Any]) -> list[dict[str, Any]]:
        out = []
        ext = [i for i in a.get("ips", []) if not is_internal(i)]
        why = f"{a['ref']} is rated {a['severity']}."
        rid = a["rule_id"]
        if rid == "R-AUTH-002":
            out.append({"action": f"Consider forcing a credential reset and revoking active sessions for {', '.join(a.get('usernames', [])) or 'the account'} once the login is confirmed unexpected.",
                        "justification": why + " A successful login followed repeated failures.", "refs": [a["ref"]]})
        if rid in ("R-AUTH-001", "R-NET-001") and ext:
            out.append({"action": f"Consider rate-limiting or blocking {ext[0]} at the perimeter if it is not a known system.",
                        "justification": why + " The source showed hostile-looking behavior in the logs; validate ownership first.", "refs": [a["ref"]]})
        if rid in ("R-NET-002", "R-NET-003"):
            out.append({"action": "Consider restricting egress for the internal host involved while its traffic is reviewed.",
                        "justification": why + " Data may have been sent to an external or watchlisted address.", "refs": [a["ref"]]})
        if rid == "R-COR-001" and a["severity"] == "Critical":
            out.append({"action": "Consider isolating the affected host(s) following your incident response plan after scoping the activity.",
                        "justification": why + " Multiple independent detections converge, including a login success and data egress or sensitive access attempts.", "refs": [a["ref"]]})
        return out
