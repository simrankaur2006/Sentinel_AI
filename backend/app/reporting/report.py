"""Deterministic incident report generation (JSON + Markdown) from stored data.

Given the same context, analysis and `generated_at`, the output is byte-for-byte identical.
"""
from __future__ import annotations

import re
from datetime import datetime
from typing import Any

from app import __version__
from app.mitre.mapping import merge_mappings

DISCLAIMER = ("Generated by SentinelAI from stored alerts and log events. Detections are leads, not proof of compromise. "
              "MITRE ATT&CK associations are hypotheses. Any AI-assisted section is advisory and must be verified against the cited evidence.")
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


def _t(v: Any, limit: int = 300) -> str:
    """Make untrusted text safe for inline Markdown."""
    s = _CTRL.sub(" ", "" if v is None else str(v)).replace("\r", " ").replace("\n", " ")
    s = s.replace("\\", "\\\\").replace("|", "\\|").replace("`", "'").replace("<", "&lt;").replace(">", "&gt;")
    return s[:limit] + ("…" if len(s) > limit else "")


def build_report(context: dict[str, Any], analysis: dict[str, Any] | None, generated_at: datetime) -> dict[str, Any]:
    inc, alerts, events = context["incident"], context["alerts"], context["events"]
    by_event: dict[str, list[str]] = {}
    for a in alerts:
        for r in a.get("event_refs", []):
            by_event.setdefault(r, []).append(a["ref"])
    timeline = [{"timestamp": e["timestamp"], "event_ref": e["ref"], "summary": _summarize(e), "alerts": by_event.get(e["ref"], [])}
                for e in sorted(events, key=lambda x: (x["timestamp"], x["ref"]))]
    sev_counts = {s: sum(1 for a in alerts if a["severity"] == s) for s in ("Critical", "High", "Medium", "Low")}
    return {
        "report_version": "1.0",
        "generated_at": generated_at.isoformat(),
        "generator": {"application": "SentinelAI", "version": __version__, "analysis_generator": (analysis or {}).get("generator", "none")},
        "incident": inc,
        "summary": {
            "alert_count": len(alerts), "severity_counts": sev_counts,
            "first_seen": min((a["first_seen"] for a in alerts), default=None), "last_seen": max((a["last_seen"] for a in alerts), default=None),
            "users": sorted({u for a in alerts for u in a.get("usernames", [])}),
            "ips": sorted({i for a in alerts for i in a.get("ips", [])}),
            "evidence_events_included": len(events),
            "evidence_events_total": sum(a.get("evidence_total", 0) for a in alerts),
        },
        "alerts": alerts,
        "mitre": merge_mappings([a.get("mitre", []) for a in alerts]),
        "timeline": timeline,
        "analyst_notes": context.get("notes", []),
        "ai_analysis": analysis,
        "disclaimer": DISCLAIMER,
    }


def _summarize(e: dict[str, Any]) -> str:
    parts = [e.get("event_type"), e.get("action"), e.get("status")]
    head = " / ".join(p for p in parts if p) or "event"
    who = " ".join(x for x in (f"user={e['username']}" if e.get("username") else "", f"src={e['source_ip']}" if e.get("source_ip") else "",
                               f"dst={e['destination_ip']}" if e.get("destination_ip") else "",
                               f"port={e['port']}" if e.get("port") is not None else "",
                               f"sent={e['bytes_sent']}B" if e.get("bytes_sent") is not None else "") if x)
    return f"{head}: {who}".strip()


def render_markdown(r: dict[str, Any]) -> str:
    inc, s = r["incident"], r["summary"]
    L: list[str] = []
    a = L.append
    a(f"# Incident Report: {_t(inc['ref'])} {_t(inc['title'], 200)}")
    a("")
    a(f"- **Generated:** {r['generated_at']}")
    a(f"- **Status:** {_t(inc['status'])}   **Severity:** {_t(inc['severity'])}")
    a(f"- **Alerts:** {s['alert_count']} (" + ", ".join(f"{v} {k}" for k, v in s["severity_counts"].items() if v) + ")")
    a(f"- **Activity window (UTC):** {s['first_seen'] or 'n/a'} to {s['last_seen'] or 'n/a'}")
    a(f"- **Users:** {_t(', '.join(s['users']) or 'none recorded')}")
    a(f"- **IPs:** {_t(', '.join(s['ips']) or 'none recorded')}")
    a(f"- **Analysis generator:** {_t(r['generator']['analysis_generator'])}")
    a("")
    if inc.get("description"):
        a("## Description"); a(""); a(_t(inc["description"], 2000)); a("")
    ai = r.get("ai_analysis")
    if ai:
        a("## Analysis summary"); a("")
        a(f"> {_t(ai['advisory_notice'], 500)}")
        a(f"> Generator: **{_t(ai['generator'])}**" + (f" (fallback reason: {_t(ai['fallback_reason'], 300)})" if ai.get("fallback_reason") else ""))
        a(""); a(_t(ai["summary"], 3000)); a("")
        for w in ai.get("warnings", []):
            a(f"- Warning: {_t(w, 500)}")
        if ai.get("warnings"): a("")
        a("### Observed facts"); a("")
        for f in ai["observed_facts"]:
            a(f"- {_t(f['text'], 600)} _(refs: {_t(', '.join(f.get('refs', [])[:8]))})_")
        a(""); a("### Hypotheses (not established facts)"); a("")
        for h in ai["hypotheses"]:
            a(f"- {_t(h['text'], 600)} _(refs: {_t(', '.join(h.get('refs', [])))})_")
        a(""); a("### Investigation steps"); a("")
        for i, st in enumerate(ai["investigation_steps"], 1):
            a(f"{i}. {_t(st, 500)}")
        a(""); a("### Containment considerations"); a("")
        for c in ai["containment"] or []:
            a(f"- {_t(c['action'], 500)} Reason: {_t(c.get('justification', ''), 500)}")
        if not ai["containment"]: a("- None justified by the current evidence.")
        a(""); a("### Missing evidence"); a("")
        for m in ai["missing_evidence"]:
            a(f"- {_t(m, 500)}")
        a("")
    a("## Alerts"); a("")
    for al in r["alerts"]:
        a(f"### {_t(al['ref'])} {_t(al['title'], 200)}")
        a("")
        a(f"- **Severity:** {_t(al['severity'])}   **Status:** {_t(al['status'])}   **Source:** {_t(al['detection_source'])} ({_t(al['rule_id'])})")
        kind = "heuristic strength (not a probability)" if al["confidence_kind"] == "heuristic_strength" else "normalized anomaly score (relative, not a probability)"
        a(f"- **Indicator:** {al['confidence']} — {kind}")
        a(f"- **Window (UTC):** {al['first_seen']} to {al['last_seen']}")
        a(f"- **Users:** {_t(', '.join(al.get('usernames', [])) or 'n/a')}   **IPs:** {_t(', '.join(al.get('ips', [])) or 'n/a')}")
        a(f"- **Why flagged:** {_t(al['explanation'], 800)}")
        a(f"- **Limitations:** {_t(al.get('limitations', ''), 600)}")
        a(f"- **Evidence events:** {_t(', '.join(al.get('event_refs', [])[:30]))}" + (" …" if al.get("evidence_total", 0) > 30 else "") + f" ({al.get('evidence_total', 0)} total)")
        a("")
    a("## MITRE ATT&CK associations"); a("")
    if r["mitre"]:
        a("| Technique | Tactic(s) | Relation | Observed behavior | Why |"); a("|---|---|---|---|---|")
        for m in r["mitre"]:
            a(f"| [{_t(m['technique_id'])}]({m['url']}) {_t(m['technique_name'])} | {_t(', '.join(t['name'] for t in m['tactics']))} | {_t(m['relation'])} | {_t(m['observed_behavior'], 250)} | {_t(m['rationale'], 300)} |")
        a(""); a("_Associations are hypotheses. 'behavior_consistent' means the logs match the technique's pattern, not that an adversary used it._")
    else:
        a("No MITRE ATT&CK mappings are supported by the evidence.")
    a(""); a("## Timeline (UTC)"); a("")
    a("| Time | Event | Summary | Alerts |"); a("|---|---|---|---|")
    for t in r["timeline"][:200]:
        a(f"| {t['timestamp']} | {_t(t['event_ref'])} | {_t(t['summary'], 200)} | {_t(', '.join(t['alerts']))} |")
    if len(r["timeline"]) >= 200: a(""); a("_Timeline limited to the first 200 events._")
    a(""); a("## Analyst notes"); a("")
    for n in r["analyst_notes"]:
        a(f"- **{_t(n['author'])}** ({n['created_at']}): {_t(n['body'], 1500)}")
    if not r["analyst_notes"]: a("No analyst notes recorded.")
    a(""); a("---"); a(f"_{r['disclaimer']}_"); a("")
    return "\n".join(L)
